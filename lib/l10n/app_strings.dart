import 'package:flutter/widgets.dart';

/// Locales offered in Settings, matching Acorn Video Downloader.
enum AppLocale {
  ku,
  tr,
  ar,
  en,
  ru,
  fr,
  fa,
  de,
  vi,
  ja,
  zh;

  static AppLocale parse(String? raw) {
    for (final value in values) {
      if (value.name == raw) return value;
    }
    return AppLocale.en;
  }

  Locale get flutterLocale => switch (this) {
    AppLocale.ku => const Locale('ku'),
    AppLocale.tr => const Locale('tr'),
    AppLocale.ar => const Locale('ar'),
    AppLocale.en => const Locale('en'),
    AppLocale.ru => const Locale('ru'),
    AppLocale.fr => const Locale('fr'),
    AppLocale.fa => const Locale('fa'),
    AppLocale.de => const Locale('de'),
    AppLocale.vi => const Locale('vi'),
    AppLocale.ja => const Locale('ja'),
    AppLocale.zh => const Locale('zh'),
  };

  String get nativeName => switch (this) {
    AppLocale.ku => 'Kurmancî',
    AppLocale.tr => 'Türkçe',
    AppLocale.ar => 'العربية',
    AppLocale.en => 'English',
    AppLocale.ru => 'Русский',
    AppLocale.fr => 'Français',
    AppLocale.fa => 'فارسی',
    AppLocale.de => 'Deutsch',
    AppLocale.vi => 'Tiếng Việt',
    AppLocale.ja => '日本語',
    AppLocale.zh => '中文',
  };

  /// Bundled PNG so flags stay visible after a locale / RTL switch.
  String get flagAsset => 'assets/flags/$name.png';

  bool get isRtl => this == AppLocale.ar || this == AppLocale.fa;
}

/// Lookup table for the current locale, falling back to English.
class AppStrings {
  const AppStrings(this.locale);

  final AppLocale locale;

  static const en = AppStrings(AppLocale.en);

  String operator [](String key) =>
      _tables[locale]?[key] ?? _en[key] ?? key;

  String format(String key, Map<String, String> args) {
    var out = this[key];
    args.forEach((name, value) {
      out = out.replaceAll('{$name}', value);
    });
    return out;
  }
}

